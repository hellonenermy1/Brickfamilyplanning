import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync('src/parent-beta.ts','utf8');
const start=source.indexOf('function p2TrackingDiagnosis(x,now){');
const end=source.indexOf('const p2OriginalRenderSnapshot=renderSnapshot;',start);
assert(start>0&&end>start,'parent tracking diagnosis must be installed');
const dom={p2TrackingDiagnosis:{className:'',textContent:'',dataset:{}},p2TrackingEvidence:{textContent:''}};
const scope=vm.createContext({Math,Number,Date,document:{getElementById:id=>dom[id]}});
vm.runInContext(source.slice(start,end),scope,{timeout:1000});
const classify=scope.p2TrackingDiagnosis;
const now=Date.UTC(2026,10,7,0,0,0);
const healthy={health:{receivedAt:now-1000,locationEnabled:true,fineLocationPermission:true,locationSubscribed:true,pendingRecords:0,ackAgeMs:1000},latest:{wallTimeMs:now-2000,receivedAt:now-1000},derived:{deviceStatus:'healthy',positionStatus:'fresh'}};
const copy=o=>structuredClone(o);
assert.equal(classify(healthy,now).code,'recent_evidence');
assert.equal(classify(null,now).code,'no_health_receipt');
assert.equal(classify({...healthy,health:{...healthy.health,receivedAt:now-140000}},now).code,'health_heartbeat_stale');
assert.equal(classify({...healthy,health:{...healthy.health,locationEnabled:false}},now).code,'location_disabled');
assert.equal(classify({...healthy,health:{...healthy.health,fineLocationPermission:false}},now).code,'precise_permission_missing');
assert.equal(classify({...healthy,health:{...healthy.health,locationSubscribed:false}},now).code,'location_subscription_missing');
assert.equal(classify({...healthy,health:{...healthy.health,pendingRecords:42,ackAgeMs:600000}},now).code,'upload_backlog');
assert.equal(classify({...healthy,latest:{}},now).code,'no_fix_receipt');
assert.equal(classify({...healthy,latest:{wallTimeMs:now-160000,receivedAt:now-2000}},now).code,'gps_capture_stale');
assert.equal(classify({...healthy,latest:{wallTimeMs:now-3000,receivedAt:now-105000}},now).code,'server_receipt_stale');
assert.equal(classify({...healthy,derived:{deviceStatus:'offline',positionStatus:'stale'}},now).code,'device_offline');
assert.equal(classify({...healthy,derived:{deviceStatus:'degraded',positionStatus:'stale'}},now).code,'position_degraded');
const before=copy(healthy);scope.p2DisplayTrackingDiagnosis(healthy,now);
assert.equal(dom.p2TrackingDiagnosis.dataset.reason,'recent_evidence');
assert.match(dom.p2TrackingEvidence.textContent,/pending records 0/);
assert.deepEqual(healthy,before,'diagnosis must never modify signed readings');
assert(!dom.p2TrackingEvidence.textContent.includes('latitude'),'diagnostics must not log private coordinates');
const future=copy(healthy);future.health.receivedAt=now+600000;
assert.equal(classify(future,now).code,'no_health_receipt','invalid future time cannot masquerade as current evidence');
console.log('PASS Phase2 tracking pipeline: stage diagnosis, delayed uploads, false-green prevention, privacy, no source mutations');
