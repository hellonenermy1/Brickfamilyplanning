import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {mergeR2LifecycleRules} from "./phase8d-r2-lifecycle-merge.mjs";
const raw={id:"user-reports-365d",enabled:true,conditions:{prefix:"reports/"},deleteObjectsTransition:{condition:{type:"Age",maxAge:365*86400}}};
const multipart={id:"bucket-multipart-cleanup",enabled:true,conditions:{prefix:""},abortMultipartUploadsTransition:{condition:{type:"Age",maxAge:7*86400}}};
const target=JSON.parse(readFileSync("audit/phase8d/PHASE8D_R2_LIFECYCLE_TARGET.json","utf8")).rules;
const evidence={id:"brick-raw-evidence-30d",enabled:true,conditions:{prefix:"evidence/raw/"},deleteObjectsTransition:{condition:{type:"Age",maxAge:30*86400}}};
const desired=[...target,evidence];
const previous={id:target[0].id,enabled:true,conditions:{prefix:"history/raw/"},deleteObjectsTransition:{condition:{type:"Age",maxAge:120*86400}}};
const merged=mergeR2LifecycleRules([raw,multipart,previous],desired);
assert.deepEqual(merged.find(x=>x.id===raw.id),raw,"user's unrelated rule lost");
assert.deepEqual(merged.find(x=>x.id===multipart.id),multipart,"multipart config lost");
for(const d of desired)assert.deepEqual(merged.find(x=>x.id===d.id),d,"Brick rule missing or stale");
assert.equal(merged.length,5);
assert.throws(()=>mergeR2LifecycleRules([{id:"global-expiry",enabled:true,conditions:{prefix:""},deleteObjectsTransition:{condition:{type:"Age",maxAge:1}}}],desired),/overlaps/);
assert.throws(()=>mergeR2LifecycleRules([{id:"other-expiry",enabled:true,conditions:{prefix:"history/"},deleteObjectsTransition:{condition:{type:"Age",maxAge:1}}}],desired),/overlaps/);
assert.throws(()=>mergeR2LifecycleRules(null,desired),/invalid/);
assert.throws(()=>mergeR2LifecycleRules([raw,raw],desired),/duplicate/);
const setup=readFileSync("scripts/setup-v1-phase6.mjs","utf8");
assert.match(setup,/mergeR2LifecycleRules\(current\.rules, desiredRules\)/);
assert.match(setup,/await cf\(endpoint\)/,"must read live policy before PUT");
assert.match(setup,/brick-raw-history-30d/);
assert.match(setup,/brick-trusted-history-90d/);
console.log("PASS 8D.17: lifecycle merge preserves unrelated rules, repairs Brick target, rejects conflicting expiration and malformed response; deployed policy still UNKNOWN");
