import assert from "node:assert/strict";
import fs from "node:fs";
const production=JSON.parse(fs.readFileSync("wrangler.template.jsonc","utf8"));
const development=JSON.parse(fs.readFileSync("wrangler.development.template.jsonc","utf8"));
const names=(arr)=>arr.map(x=>x.name);
const sorted=(xs)=>xs.slice().sort();
const expectedProd=["DB","BRICK_DEVICE","HISTORY","MAPS","EVENTS","DEVICE_RATE","PAIR_RATE","PARENT_HISTORY_RATE","PARENT_WS_RATE","PARENT_GEOCODE_RATE","PARENT_COMMUTE_RATE"];
const expectedDev=["DB","BRICK_DEVICE","DEVICE_RATE","PAIR_RATE","PARENT_HISTORY_RATE","PARENT_WS_RATE","PARENT_GEOCODE_RATE","PARENT_COMMUTE_RATE","PARENT_LOGIN_RATE"];
const b=(conf)=>[...conf.d1_databases.map(x=>x.binding),...conf.durable_objects.bindings.map(x=>x.name),...(conf.r2_buckets||[]).map(x=>x.binding),...(conf.queues?.producers||[]).map(x=>x.binding),...(conf.ratelimits||[]).map(x=>x.name)];
assert.deepEqual(sorted(b(production)),sorted(expectedProd),"production binding list drift");
assert.deepEqual(sorted(b(development)),sorted(expectedDev),"development binding list drift");
assert.equal(production.name,"brick-family-v1");
assert.equal(production.main,"src/worker-p8b.ts");
assert.equal(production.vars.APP_ENV,"production");
assert.equal(production.d1_databases.length,1);
assert.equal(production.d1_databases[0].binding,"DB");
assert.equal(production.d1_databases[0].database_name,"brick-family-v1");
assert.equal(production.r2_buckets.find(x=>x.binding==="HISTORY").bucket_name,"brick-family-v1-history");
assert.equal(production.r2_buckets.find(x=>x.binding==="MAPS").bucket_name,"brick-family-v1-maps");
assert.equal(production.queues.producers.find(x=>x.binding==="EVENTS").queue,"brick-family-v1-events");
const consumers=production.queues.consumers;
const main=consumers.find(x=>x.queue==="brick-family-v1-events");
const dead=consumers.find(x=>x.queue==="brick-family-v1-dlq");
assert(main&&dead,"mandatory event/DLQ consumers absent");
assert.equal(main.dead_letter_queue,dead.queue);
assert.equal(main.max_concurrency,1,"keep durable storage merge sequential under consumers");
assert(main.max_retries>=5&&dead.max_retries>=20,"DLQ replay bound drift");
assert.equal(development.name,"brick-family-v1-dev");
assert.equal(development.main,"src/worker-v10.ts");
assert.equal(development.vars.APP_ENV,"development");
assert.equal(development.vars.DEV_PARENT_AUTH_MODE,"d1-session-v1");
assert(development.d1_databases[0].database_name!==production.d1_databases[0].database_name);
assert(!development.queues&&!development.r2_buckets,"dev must not share production Queue/R2");
for(const conf of [production,development]){
 const ids=conf.ratelimits.map(x=>String(x.namespace_id));
 assert.equal(new Set(ids).size,ids.length,"duplicate rate namespace");
 for(const rule of conf.ratelimits)assert(Number(rule.simple?.limit)>0&&Number(rule.simple?.period)===60);
}
const overlap=production.ratelimits.map(x=>String(x.namespace_id)).filter(id=>development.ratelimits.some(x=>String(x.namespace_id)===id));
assert.equal(overlap.length,0,"production/dev rate namespace overlapping");
assert.equal(production.vars.CF_ACCESS_TEAM_DOMAIN,"__CF_ACCESS_TEAM_DOMAIN__");
assert.equal(production.vars.CF_ACCESS_AUD,"__CF_ACCESS_AUD__");
assert(production.triggers.crons.includes("*/1 * * * *"));
assert(production.triggers.crons.includes("17 3 * * *"));
console.log("PASS P8D-040: production vs development config bindings, 7 distinct prod newer quota/storage names, isolated D1/rates, Queue/DLQ retry, Access secrets and schedules are source-parity consistent. Cloudflare live drift remains OPEN.");
